// The app's security headers, defined once. Every place that
// serves the app reads them from here, so they can't drift apart:
// - `vite dev` / `vite preview` (vite.config.ts),
// - Cloudflare Pages static files, through `dist/_headers` (written by scripts/generate-headers.mjs
//   at build time; never hand-written),
// - Cloudflare Pages Functions, through functions/_middleware.ts (Pages doesn't apply `_headers`
//   to Function responses).

/** Headers sent with every response, in development too. */
export const baseHeaders: Record<string, string> = {
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'microphone=(), camera=(), geolocation=(), payment=()',
  'X-Frame-Options': 'DENY',
  // Keep the invite-only site out of search engines. This header
  // covers every response, including the API and the *.pages.dev address; public/robots.txt asks
  // crawlers not to fetch anything, and index.html carries the same rule as a <meta> tag.
  'X-Robots-Tag': 'noindex, nofollow',
}

/**
 * The one inline stylesheet the app needs, allowed by its exact hash rather than by opening
 * `style-src` to every inline style. React Aria's usePress adds this `<style>` the first time a
 * pressable control renders (`[data-react-aria-pressable] { touch-action: pan-x pan-y
 * pinch-zoom }`, so a double tap doesn't wait for zoom). If a React Aria update changes its text,
 * the hash stops matching, the browser blocks it again, and e2e/security.spec.ts fails.
 */
const REACT_ARIA_PRESS_STYLE = "'sha256-38RhXrc7EdReTKsOm23ZPOCUgniTUUcjky8QOOrQx6o='"

/**
 * Content-Security-Policy: the browser may only load scripts, styles and fonts from this app,
 * images from this app or TMDB's image host, and may not be framed by other sites. Not sent by
 * the dev server, which needs inline scripts for React Fast Refresh.
 */
export const contentSecurityPolicy = [
  "default-src 'self'",
  "script-src 'self'",
  `style-src 'self' ${REACT_ARIA_PRESS_STYLE}`,
  "img-src 'self' data: https://image.tmdb.org",
  "connect-src 'self'",
  "font-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ')

/**
 * HTTPS only, for a year, subdomains included. Hosted only: localhost is plain HTTP. No
 * `preload`, which is hard to undo and would bind the owner's whole domain.
 */
export const strictTransportSecurity = 'max-age=31536000; includeSubDomains'

/** Every header a hosted response gets: the base set, the CSP and HSTS. */
export const productionHeaders: Record<string, string> = {
  ...baseHeaders,
  'Content-Security-Policy': contentSecurityPolicy,
  'Strict-Transport-Security': strictTransportSecurity,
}

/**
 * The text of Cloudflare Pages' `_headers` file: the production headers on every path, and a
 * one-year immutable cache for `/assets/*`, whose file names change whenever their content does.
 */
export function headersFile(): string {
  const block = (path: string, headers: Record<string, string>) =>
    [path, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join('\n')
  return [
    '# GENERATED by scripts/generate-headers.mjs from server/securityHeaders.ts. Do not edit.',
    block('/*', productionHeaders),
    block('/assets/*', { 'Cache-Control': 'public, max-age=31536000, immutable' }),
    '',
  ].join('\n')
}
