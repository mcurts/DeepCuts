// Generates the app icons in public/ from the brand tokens (ADR-0040; artwork:
// docs repo: design/triple-feature/deep-cuts-favicon.svg). Run `npm run icons` after changing either.
//
// The icon is the "DC" monogram on a split tile: a blood-red left half with a bone D, and a bone
// right half (cut on a slant) with an ink C. The letters are already vector paths, so no font is
// needed.
//
// Outputs (committed, so the app needs no build step for them):
// - favicon.svg: browser tabs in every current browser
// - favicon-halloween.svg: the October tab icon, swapped in at startup (seasonalLogos.ts)
// - favicon.ico: a 32px PNG wrapped in an ICO header, for older browsers and tools that ask for
//   /favicon.ico by name
// - apple-touch-icon.png (180), icon-192.png, icon-512.png: home screens (phones round the
//   corners themselves), rendered from the SVG with Playwright's Chromium
// - manifest.webmanifest: name, icons and colors for "Add to Home Screen"
import { chromium } from '@playwright/test'
import { readFileSync, writeFileSync } from 'node:fs'

const tokens = JSON.parse(readFileSync('build/tokens/tokens.json', 'utf8'))
const color = {
  // The default theme's logo roles (ADR-0056): first block, its letters, second block, its letters.
  red: tokens['brand-logo-primary'],
  bone: tokens['brand-logo-on-primary'],
  boneBlock: tokens['brand-logo-secondary'],
  ink: tokens['brand-logo-on-secondary'],
  // The Halloween icon (October; src/components/layout/seasonalLogos.ts) wears the lit Halloween
  // wordmark's colors: purple and orange blocks, an orange D.
  litDeep: tokens['brand-halloween-lit-deep'],
  litCuts: tokens['brand-halloween-lit-cuts'],
  litLetters: tokens['brand-halloween-lit-letters'],
  // The app's page color, for the home-screen splash and browser UI.
  surface: tokens['color-surface-default'],
}

// The two letters on the wordmark's 50×100 grid, scaled to 48% and leaned 8° like the wordmark.
const D = 'M0 0H30Q50 0 50 20V80Q50 100 30 100H0Z M17 17V83H28Q33 83 33 78V22Q33 17 28 17Z'
const C =
  'M50 34V22Q50 0 25 0Q0 0 0 22V78Q0 100 25 100Q50 100 50 78V64H33V77Q33 84 25 84Q17 84 17 77V23Q17 16 25 16Q33 16 33 23V34Z'
const place = (x) => `translate(${x} 32) skewX(-8) translate(-12 -24) scale(0.48)`

/** The monogram tile in the given colors: left block, right block, D, C. */
const monogram = (
  left,
  right,
  d,
  c,
) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="Deep Cuts">
  <!-- GENERATED by scripts/generate-icons.mjs (npm run icons). Do not edit by hand. -->
  <rect width="64" height="64" fill="${left}"/>
  <polygon points="36.5,0 64,0 64,64 27.5,64" fill="${right}"/>
  <path fill="${d}" fill-rule="evenodd" transform="${place(15.5)}" d="${D}"/>
  <path fill="${c}" fill-rule="evenodd" transform="${place(47.5)}" d="${C}"/>
</svg>
`
const svg = monogram(color.red, color.boneBlock, color.bone, color.ink)
writeFileSync('public/favicon.svg', svg)
// Seasonal tab icons: SVG only (see applySeasonalFavicon).
writeFileSync(
  'public/favicon-halloween.svg',
  monogram(color.litDeep, color.litCuts, color.litLetters, color.ink),
)

// ---- PNGs: render the SVG at each size ----
const browser = await chromium.launch()
const page = await browser.newPage()
const render = async (px) => {
  await page.setViewportSize({ width: px, height: px })
  await page.setContent(
    `<body style="margin:0">${svg.replace('<svg ', `<svg width="${px}" height="${px}" `)}</body>`,
  )
  return page.screenshot({ omitBackground: true })
}
for (const [name, px] of [
  ['apple-touch-icon.png', 180],
  ['icon-192.png', 192],
  ['icon-512.png', 512],
]) {
  writeFileSync(`public/${name}`, await render(px))
}

// ICO: a 6-byte header and one 16-byte directory entry pointing at an embedded PNG, which every
// browser since IE11 reads.
const png = await render(32)
const ico = Buffer.alloc(22)
ico.writeUInt16LE(1, 2) // type: icon
ico.writeUInt16LE(1, 4) // one image
ico.writeUInt8(32, 6) // width
ico.writeUInt8(32, 7) // height
ico.writeUInt16LE(1, 10) // colour planes
ico.writeUInt16LE(32, 12) // bits per pixel
ico.writeUInt32LE(png.length, 14) // image size
ico.writeUInt32LE(22, 18) // image offset
writeFileSync('public/favicon.ico', Buffer.concat([ico, png]))
await browser.close()

writeFileSync(
  'public/manifest.webmanifest',
  JSON.stringify(
    {
      name: 'Deep Cuts',
      short_name: 'Deep Cuts',
      description:
        "The B-sides of cinema: a fast, one-thumb movie tracker for finding films you didn't know existed.",
      start_url: '/',
      display: 'standalone',
      background_color: color.surface,
      theme_color: color.surface,
      icons: [
        { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
        { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
      ],
    },
    null,
    2,
  ) + '\n',
)
console.log(
  'wrote public/favicon.svg, favicon-halloween.svg, favicon.ico, apple-touch-icon.png, icon-192.png, icon-512.png, manifest',
)
