// Writes the app files that come from the themes but aren't design tokens, after the token build
// (npm run tokens). The site-builder engine (tokens/engine/) writes the tokens themselves; this
// script reads its output and each theme's meta.json (label, color scheme, fonts):
//
// - src/styles/themes.ts       the list the theme chooser reads, with each theme's page color
// - src/styles/theme-fonts.css the default theme's fonts (other themes load theirs when chosen)
// - public/theme-boot.js       applies a `?theme=` link or the saved choice before the first paint
//
// See docs/design-tokens.md for how a theme is added.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { THEME_KEY } from '../src/adapters/local/themeKey.ts'
import { STORAGE_PREFIX } from '../src/adapters/local/versionedStore.ts'

const GENERATED =
  'GENERATED by scripts/theme-files.mjs from tokens/. Do not edit; change the tokens instead.'
/** Where the app saves the chosen theme (LocalThemePreference), read by the boot script. */
const THEME_STORAGE_KEY = STORAGE_PREFIX + THEME_KEY

const THEMES_DIR = 'tokens/src/themes'
/** Every theme's resolved tokens, keyed by theme id (written by the engine). */
const values = JSON.parse(readFileSync('tokens/dist/json/contexts/theme.json', 'utf8'))
const themes = readdirSync(THEMES_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => ({
    id: d.name,
    meta: JSON.parse(readFileSync(`${THEMES_DIR}/${d.name}/meta.json`, 'utf8')),
  }))
const defaults = themes.filter((t) => t.meta.default)
if (defaults.length !== 1)
  throw new Error(`exactly one theme must be the default (${defaults.length})`)
const defaultTheme = defaults[0]
// The default first, then by label, so the chooser lists the house look first.
themes.sort(
  (a, b) =>
    (b.meta.default ? 1 : 0) - (a.meta.default ? 1 : 0) || a.meta.label.localeCompare(b.meta.label),
)

/** The page color, for the browser's theme-color. */
const pageColor = (id) => values[id]['theme-color-background-default']

mkdirSync('src/styles', { recursive: true })
writeFileSync(
  'src/styles/theme-fonts.css',
  [`/* ${GENERATED} */`, ...defaultTheme.meta.fonts.map((f) => `@import '${f}';`), ''].join('\n'),
)

// Other themes' fonts are dynamic imports, so Vite splits them out of the first load.
const entry = (t) => {
  const fonts = t.meta.default ? [] : t.meta.fonts
  return [
    '  {',
    `    id: '${t.id}',`,
    `    label: '${t.meta.label}',`,
    `    colorScheme: '${t.meta.colorScheme}',`,
    `    themeColor: '${pageColor(t.id)}',`,
    `    loadFonts: ${fonts.length ? `() => Promise.all([${fonts.map((f) => `import('${f}')`).join(', ')}])` : 'undefined'},`,
    '  },',
  ].join('\n')
}
writeFileSync(
  'src/styles/themes.ts',
  [
    `// ${GENERATED}`,
    '',
    '/** One theme (brand look) the app can switch to. */',
    'export interface ThemeInfo {',
    '  /** The folder name in tokens/src/themes/, and the value of <html data-theme>. */',
    '  id: string',
    '  /** The name the chooser shows. */',
    '  label: string',
    "  colorScheme: 'light' | 'dark'",
    "  /** The page color, for the browser's theme-color. */",
    '  themeColor: string',
    "  /** Loads the theme's fonts; undefined for the default theme, whose fonts load with the app. */",
    '  loadFonts: (() => Promise<unknown>) | undefined',
    '}',
    '',
    '/** Every theme, the default first. */',
    'export const THEMES: readonly ThemeInfo[] = [',
    ...themes.map(entry),
    ']',
    '',
    '/** The theme used when none is chosen. */',
    `export const DEFAULT_THEME_ID = '${defaultTheme.id}'`,
    '',
  ].join('\n'),
)

// A classic script in <head> (index.html), external so the CSP keeps `script-src 'self'`. It runs
// before the first paint, so a returning visitor never sees the default theme flash first.
const colors = Object.fromEntries(themes.map((t) => [t.id, pageColor(t.id)]))
mkdirSync('public', { recursive: true })
writeFileSync(
  'public/theme-boot.js',
  `/* ${GENERATED} */
(function () {
  var themes = ${JSON.stringify(colors)};
  var id = new URLSearchParams(location.search).get('theme');
  try {
    if (!themes[id]) id = JSON.parse(localStorage.getItem(${JSON.stringify(THEME_STORAGE_KEY)}));
  } catch (e) {}
  if (!themes[id] || id === ${JSON.stringify(defaultTheme.id)}) return;
  document.documentElement.setAttribute('data-theme', id);
  var meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.setAttribute('content', themes[id]);
})();
`,
)
console.log(
  `✓ ${themes.length} themes → src/styles/themes.ts, theme-fonts.css, public/theme-boot.js`,
)
