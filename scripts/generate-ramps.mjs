// Generates full OKLCH ramps (50–950) for the categorical hue families.
// Output is committed (tokens/src/tier-1-definitions/hues.json) so values only change when this script is re-run on purpose.
// Run: npm run tokens:ramps
import { writeFileSync } from 'node:fs'

// Hue angles in OKLCH. The red family (~0–40°) is reserved for Dislike, so it is not generated here.
const FAMILIES = {
  orange: 62,
  gold: 85,
  lime: 125,
  green: 150,
  cyan: 205,
  sky: 235,
  indigo: 270,
  violet: 300,
  magenta: 330,
}
// Lightness per step; chroma peaks mid-ramp and is reduced until the color fits in sRGB.
const STEPS = {
  50: 0.97,
  100: 0.93,
  200: 0.88,
  300: 0.82,
  400: 0.74,
  500: 0.66,
  600: 0.57,
  700: 0.48,
  800: 0.39,
  900: 0.3,
  950: 0.22,
}
// High enough that the gamut, not this cap, limits most mid steps: the genre tones should be as
// vivid as sRGB allows. The bell curve below still calms the ends.
const MAX_CHROMA = 0.24

function oklchToSrgb(L, C, h) {
  const a = C * Math.cos((h * Math.PI) / 180)
  const b = C * Math.sin((h * Math.PI) / 180)
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
  return lin.map((c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055))
}
const inGamut = (rgb) => rgb.every((c) => c >= -1e-4 && c <= 1 + 1e-4)
const hex = (rgb) =>
  '#' +
  rgb
    .map((c) =>
      Math.round(Math.min(1, Math.max(0, c)) * 255)
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')

const color = { $type: 'color' }
for (const [name, h] of Object.entries(FAMILIES)) {
  color[name] = {}
  for (const [step, L] of Object.entries(STEPS)) {
    // A bell curve keeps the lightest and darkest steps calm.
    let C = MAX_CHROMA * (1 - Math.abs(L - 0.62) / 0.45) ** 0.6
    if (!(C > 0)) C = 0.02
    while (C > 0 && !inGamut(oklchToSrgb(L, C, h))) C -= 0.002
    color[name][step] = {
      $value: hex(oklchToSrgb(L, Math.max(C, 0), h)),
      $description: `oklch(${L} ${Math.max(C, 0).toFixed(3)} ${h})`,
    }
  }
}

writeFileSync(
  'tokens/src/tier-1-definitions/hues.json',
  JSON.stringify(
    {
      $description: 'GENERATED by scripts/generate-ramps.mjs. Do not edit by hand.',
      color,
    },
    null,
    2,
  ) + '\n',
)
console.log(
  `wrote tokens/src/tier-1-definitions/hues.json (${Object.keys(FAMILIES).length} families)`,
)
