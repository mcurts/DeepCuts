// The holiday schedule for the logo and the browser-tab icon. Each holiday is one entry: a
// recurring date window, the artwork that replaces the wordmark (Logo.tsx), and the favicon that
// replaces the standard one. The rest of the year shows the standard logo and icon.
//
// To add a holiday: draw its artwork as a component that takes LogoArtProps, add its favicon to
// scripts/generate-icons.mjs (`npm run icons`), and add an entry below.

import type { ComponentType } from 'react'
import { currentSeason, type SeasonWindow } from '@/domain/seasons'
import { HalloweenLogo } from './HalloweenLogo'
import type { LogoArtProps } from './logoGlyphs'

/** Holiday artwork that replaces the standard logo and favicon while `window` is in season. */
type SeasonalLogo = {
  id: string
  window: SeasonWindow
  Art: ComponentType<LogoArtProps>
  /** Path of the SVG favicon in public/, generated by scripts/generate-icons.mjs. */
  favicon: string
}

/** Every seasonal logo, checked in order; the first in season wins. */
export const SEASONAL_LOGOS: readonly SeasonalLogo[] = [
  // All of October.
  {
    id: 'halloween',
    window: { start: { month: 10, day: 1 }, end: { month: 10, day: 31 } },
    Art: HalloweenLogo,
    favicon: '/favicon-halloween.svg',
  },
]

/**
 * Swaps the browser-tab icon for the holiday's when one is in season. Call once at startup;
 * the date is checked then, like the logo's. Only the SVG icon changes: it's the one current
 * browsers show. Safari, which mostly ignores SVG favicons, and the home-screen icons (fixed once
 * installed) keep the standard artwork.
 */
export function applySeasonalFavicon(date = new Date(), doc: Document = document) {
  const favicon = currentSeason(SEASONAL_LOGOS, date)?.favicon
  const link = doc.querySelector<HTMLLinkElement>('link[rel="icon"][type="image/svg+xml"]')
  if (favicon && link) link.href = favicon
}
