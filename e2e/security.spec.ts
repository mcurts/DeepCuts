// End-to-end security checks against the production build: the Content-Security-Policy and other
// security headers are sent, the page loads without CSP violations, and the TMDB proxy refuses
// anything outside its allowlist (ADR-0008).
import { expect, test } from '@playwright/test'

// ADR-0008: strict CSP and security headers on the production build.
test('serves a strict Content-Security-Policy and security headers', async ({ request }) => {
  const res = await request.get('/')
  const h = res.headers()
  const csp = h['content-security-policy'] ?? ''
  expect(csp).toContain("default-src 'self'")
  expect(csp).toContain("script-src 'self'")
  expect(csp).toContain("frame-ancestors 'none'")
  expect(csp).toContain("object-src 'none'")
  expect(csp).not.toContain('unsafe-inline')
  expect(csp).not.toContain('unsafe-eval')
  expect(csp).not.toMatch(/frame-src/) // ADR-0018: no embeds
  expect(h['x-content-type-options']).toBe('nosniff')
  expect(h['x-frame-options']).toBe('DENY')
  expect(h['referrer-policy']).toBe('strict-origin-when-cross-origin')
  expect(h['permissions-policy']).toContain('microphone=()')
})

// Owner, 2026-10-07: no search engines yet. Header, robots.txt and <meta> all say so.
test('asks search engines to stay away', async ({ request, page }) => {
  expect((await request.get('/')).headers()['x-robots-tag']).toBe('noindex, nofollow')
  const robots = await request.get('/robots.txt')
  expect(robots.status()).toBe(200)
  expect(await robots.text()).toMatch(/User-agent: \*\s+Disallow: \/\s*$/)
  await page.goto('/')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'noindex, nofollow')
})

test('serves the app icons and manifest (generated by npm run icons)', async ({ request }) => {
  for (const path of [
    '/favicon.svg',
    '/apple-touch-icon.png',
    '/icon-192.png',
    '/icon-512.png',
    '/manifest.webmanifest',
  ]) {
    expect((await request.get(path)).status(), path).toBe(200)
  }
})

// The browser's securitypolicyviolation event, not just console errors: a blocked attempt that
// the code catches (Zod's eval probe) logs nothing but is still reported, and Lighthouse counts it.
// Detail is visited too, because React Aria's inline press style only appears once a pressable
// control renders. Sign in and Register are visited for their forms. These run signed out, so the
// signed-in pages (My Lists, Account) would only redirect to Sign in.
for (const [path, pressable] of [
  ['/', false],
  ['/movie/1091', true],
  ['/sign-in', true],
  ['/register', true],
] as const) {
  test(`${path} loads with no CSP violations`, async ({ page }) => {
    await page.addInitScript(() => {
      const w = window as unknown as { cspViolations: string[] }
      w.cspViolations = []
      document.addEventListener('securitypolicyviolation', (e) =>
        w.cspViolations.push(`${e.violatedDirective} ${e.blockedURI} ${e.sourceFile}`),
      )
    })
    await page.goto(path)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    if (pressable) await expect(page.getByRole('button').first()).toBeVisible()
    expect(
      await page.evaluate(() => (window as unknown as { cspViolations: string[] }).cspViolations),
    ).toEqual([])
  })
}

test('the TMDB proxy refuses endpoints outside the allowlist', async ({ request, baseURL }) => {
  expect((await request.get('/api/tmdb/account')).status()).toBe(404)
  expect((await request.get('/api/tmdb/search/movie?query=a&api_key=x')).status()).toBe(400)
  // Sent with this site's own Origin, as a browser would; the hosted API refuses other origins
  // first (403, see hosting.spec.ts).
  const post = await request.post('/api/tmdb/genre/movie/list', {
    headers: { Origin: new URL(baseURL ?? '').origin },
  })
  expect(post.status()).toBe(405)
})
