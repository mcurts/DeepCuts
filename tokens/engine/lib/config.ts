/**
 * Loads tokens.config.json and fills in defaults. The config says what to build; the
 * resolver document says what the tokens are. Validation here is structural only.
 * Whether the inputs name real modifiers and contexts is checked against the resolver
 * (resolver.ts), because only it knows them.
 */
import { readFileSync } from 'node:fs';
import type { ContextOutput, EngineConfig } from './types.ts';

type RawConfig = Partial<Omit<EngineConfig, 'css' | 'outputs' | 'grammar' | 'contrast' | 'fluid'>> & {
  fluid?: Partial<EngineConfig['fluid']>;
  css?: Partial<Omit<EngineConfig['css'], 'contexts'>> & { contexts?: Partial<ContextOutput>[] };
  outputs?: Partial<EngineConfig['outputs']>;
  grammar?: Partial<EngineConfig['grammar']>;
  contrast?: Partial<EngineConfig['contrast']>;
};

export class ConfigError extends Error {}

/** Parse and complete a config object. Throws ConfigError naming the first problem. */
export function parseConfig(raw: RawConfig): EngineConfig {
  if (!raw.name || !/^[a-z][a-z0-9-]*$/.test(raw.name)) {
    throw new ConfigError('tokens.config.json: "name" must be a kebab-case site name.');
  }
  if (!raw.input || typeof raw.input !== 'object') {
    throw new ConfigError('tokens.config.json: "input" must choose one context per modifier.');
  }
  const permutations = raw.css?.permutations ?? [];
  permutations.forEach((p, i) => {
    if (!p.selector && !p.media) throw new ConfigError(`tokens.config.json: css.permutations[${i}] needs a "selector", a "media" query, or both.`);
  });
  const contexts = (raw.css?.contexts ?? []).map((c, i): ContextOutput => {
    if (!c.modifier || !c.selector?.includes('{context}')) {
      throw new ConfigError(`tokens.config.json: css.contexts[${i}] needs "modifier" and a "selector" containing {context}.`);
    }
    for (const name of c.permutations ?? []) {
      if (!permutations.some((p) => p.name === name)) throw new ConfigError(`tokens.config.json: css.contexts[${i}] applies unknown permutation "${name}".`);
    }
    return {
      modifier: c.modifier,
      selector: c.selector,
      file: c.file ?? 'separate',
      diff: c.diff ?? true,
      ...(c.rules && { rules: c.rules }),
      permutations: c.permutations ?? [],
      ...(c.declarations && { declarations: c.declarations }),
    };
  });
  return {
    name: raw.name,
    banner: raw.banner ?? `Generated by the site-builder token engine for ${raw.name}. Do not edit; change the DTCG source.`,
    extensionNamespace: raw.extensionNamespace ?? 'com.mikecurts',
    input: raw.input,
    css: {
      layer: raw.css?.layer === undefined ? 'tokens' : raw.css.layer,
      root: raw.css?.root ?? ':root',
      ...(raw.css?.declarations && { declarations: raw.css.declarations }),
      permutations,
      contexts,
    },
    outputs: {
      email: raw.outputs?.email ?? false,
      tailwind: raw.outputs?.tailwind ?? null,
    },
    fluid: { minPx: raw.fluid?.minPx ?? 360, maxPx: raw.fluid?.maxPx ?? 1440 },
    grammar: {
      categories: raw.grammar?.categories ?? {},
      allowedValueWords: raw.grammar?.allowedValueWords ?? {},
    },
    contrast: {
      alsoRequired: raw.contrast?.alsoRequired ?? [],
      permutations: raw.contrast?.permutations ?? 'each',
    },
  };
}

export const loadConfig = (file: string): EngineConfig =>
  parseConfig(JSON.parse(readFileSync(file, 'utf8')) as RawConfig);
